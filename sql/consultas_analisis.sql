/* ============================ PACKAGE BODY ============================ */

FUNCTION FIDE_CONSULTAS_DASHBOARD_FN(
    P_ID_TEMPORADA IN FIDE_TEMPORADAS_TB.ID_TEMPORADA%TYPE,
    P_ID_CATEGORIA IN FIDE_CATEGORIAS_TB.ID_CATEGORIA%TYPE
) RETURN CLOB
IS
    V_JSON CLOB;
    V_PRIMER_ITEM BOOLEAN := TRUE;

    CURSOR C_DASHBOARD IS
        SELECT JSON_OBJECT(
            'TOTAL_JUGADORES' VALUE (SELECT COUNT(*) FROM FIDE_JUGADORES_BUSQUEDA_CONSULTA_V J WHERE J.ID_ESTADO = 1 AND (P_ID_CATEGORIA IS NULL OR J.ID_CATEGORIA = P_ID_CATEGORIA)),
            'TOTAL_PARTIDOS' VALUE COUNT(*),
            'PARTIDOS_GANADOS' VALUE NVL(SUM(CASE WHEN R.RESULTADO = 'ganado' THEN 1 ELSE 0 END), 0),
            'GOLES_FAVOR' VALUE NVL(SUM(R.GOLES_FAVOR), 0),
            'TOTAL_ASISTENCIAS' VALUE NVL((SELECT SUM(E.ASISTENCIAS) FROM FIDE_JUGADORES_TEMPORADA_CONSULTA_V E WHERE (P_ID_TEMPORADA IS NULL OR E.ID_TEMPORADA = P_ID_TEMPORADA) AND (P_ID_CATEGORIA IS NULL OR E.ID_CATEGORIA = P_ID_CATEGORIA)), 0),
            'TOTAL_LESIONES' VALUE NVL((SELECT SUM(D.LESIONES) FROM FIDE_DISPONIBILIDAD_CONSULTA_V D WHERE P_ID_CATEGORIA IS NULL OR D.ID_CATEGORIA = P_ID_CATEGORIA), 0),
            'TOTAL_DISPONIBLES' VALUE NVL((SELECT COUNT(*) FROM FIDE_DISPONIBILIDAD_CONSULTA_V D WHERE D.ESTADO = 'DISPONIBLE' AND (P_ID_CATEGORIA IS NULL OR D.ID_CATEGORIA = P_ID_CATEGORIA)), 0),
            'TOP_GOLEADOR_NOMBRE' VALUE (SELECT MAX(X.NOMBRE_COMPLETO) KEEP (DENSE_RANK FIRST ORDER BY X.GOLES DESC) FROM (SELECT E.NOMBRE_COMPLETO, SUM(E.GOLES) AS GOLES FROM FIDE_JUGADORES_TEMPORADA_CONSULTA_V E WHERE (P_ID_TEMPORADA IS NULL OR E.ID_TEMPORADA = P_ID_TEMPORADA) AND (P_ID_CATEGORIA IS NULL OR E.ID_CATEGORIA = P_ID_CATEGORIA) GROUP BY E.ID_JUGADOR, E.NOMBRE_COMPLETO) X),
            'TOP_GOLEADOR_GOLES' VALUE NVL((SELECT MAX(X.GOLES) FROM (SELECT SUM(E.GOLES) AS GOLES FROM FIDE_JUGADORES_TEMPORADA_CONSULTA_V E WHERE (P_ID_TEMPORADA IS NULL OR E.ID_TEMPORADA = P_ID_TEMPORADA) AND (P_ID_CATEGORIA IS NULL OR E.ID_CATEGORIA = P_ID_CATEGORIA) GROUP BY E.ID_JUGADOR) X), 0),
            'TOP_ASISTENTE_NOMBRE' VALUE (SELECT MAX(X.NOMBRE_COMPLETO) KEEP (DENSE_RANK FIRST ORDER BY X.ASISTENCIAS DESC) FROM (SELECT E.NOMBRE_COMPLETO, SUM(E.ASISTENCIAS) AS ASISTENCIAS FROM FIDE_JUGADORES_TEMPORADA_CONSULTA_V E WHERE (P_ID_TEMPORADA IS NULL OR E.ID_TEMPORADA = P_ID_TEMPORADA) AND (P_ID_CATEGORIA IS NULL OR E.ID_CATEGORIA = P_ID_CATEGORIA) GROUP BY E.ID_JUGADOR, E.NOMBRE_COMPLETO) X),
            'TOP_ASISTENTE_ASISTENCIAS' VALUE NVL((SELECT MAX(X.ASISTENCIAS) FROM (SELECT SUM(E.ASISTENCIAS) AS ASISTENCIAS FROM FIDE_JUGADORES_TEMPORADA_CONSULTA_V E WHERE (P_ID_TEMPORADA IS NULL OR E.ID_TEMPORADA = P_ID_TEMPORADA) AND (P_ID_CATEGORIA IS NULL OR E.ID_CATEGORIA = P_ID_CATEGORIA) GROUP BY E.ID_JUGADOR) X), 0)
            RETURNING CLOB
        ) AS ITEM
        FROM FIDE_PARTIDOS_RESUMEN_CONSULTA_V R
        WHERE R.ID_ESTADO = 1
          AND (P_ID_TEMPORADA IS NULL OR R.ID_TEMPORADA = P_ID_TEMPORADA)
