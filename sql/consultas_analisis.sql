/*
    Consultas deportivas simplificadas.

    Primero se crean las vistas. Despues se agregan las declaraciones de la
    seccion PACKAGE SPEC y los cuerpos de la seccion PACKAGE BODY al paquete
    FIDE_PROYECTOFINALACADEMIALEIVA_PCK existente.

    Las funciones solo filtran una vista y recorren un cursor explicito. Los
    calculos repetidos quedan centralizados en las vistas.
*/

/* ============================ VISTAS ============================ */

CREATE OR REPLACE FORCE VIEW FIDE_JUGADORES_BUSQUEDA_CONSULTA_V AS
SELECT
    J.ID_JUGADOR,
    J.CEDULA,
    J.ID_CATEGORIA,
    C.NOMBRE_CATEGORIA,
    J.NOMBRE,
    J.APELLIDO_PATERNO,
    J.APELLIDO_MATERNO,
    J.DORSAL,
    J.ID_ESTADO,
    NVL(POS.POSICIONES, 'Sin posicion') AS POSICIONES,
    NVL(PAR.PARTIDOS_JUGADOS, 0) AS PARTIDOS_JUGADOS,
    NVL(LES.LESIONES, 0) AS LESIONES
FROM FIDE_JUGADORES_TB J
LEFT JOIN FIDE_CATEGORIAS_TB C ON C.ID_CATEGORIA = J.ID_CATEGORIA
LEFT JOIN (
    SELECT JP.ID_JUGADOR,
           LISTAGG(P.NOMBRE_POSICION, ', ') WITHIN GROUP (ORDER BY P.NOMBRE_POSICION) AS POSICIONES
    FROM FIDE_JUGADOR_POSICIONES_TB JP
    JOIN FIDE_POSICIONES_TB P ON P.ID_POSICION = JP.ID_POSICION
    WHERE JP.ID_ESTADO = 1
      AND P.ID_ESTADO = 1
    GROUP BY JP.ID_JUGADOR
) POS ON POS.ID_JUGADOR = J.ID_JUGADOR
LEFT JOIN (
    SELECT A.ID_JUGADOR, COUNT(DISTINCT A.ID_PARTIDO) AS PARTIDOS_JUGADOS
    FROM FIDE_ASISTENCIA_TB A
    WHERE A.ID_ESTADO = 1
    GROUP BY A.ID_JUGADOR
) PAR ON PAR.ID_JUGADOR = J.ID_JUGADOR
LEFT JOIN (
    SELECT PM.ID_JUGADOR, COUNT(DISTINCT L.ID_LESION) AS LESIONES
    FROM FIDE_PARTE_MEDICO_TB PM
    JOIN FIDE_LESIONES_TB L ON L.ID_PARTEMEDICO = PM.ID_PARTEMEDICO
    WHERE PM.ID_ESTADO = 1
      AND L.ID_ESTADO = 1
    GROUP BY PM.ID_JUGADOR
) LES ON LES.ID_JUGADOR = J.ID_JUGADOR;

CREATE OR REPLACE FORCE VIEW FIDE_JUGADORES_RENDIMIENTO_CONSULTA_V AS
SELECT
    J.ID_JUGADOR,
    J.CEDULA,
    J.NOMBRE,
    J.APELLIDO_PATERNO,
    J.APELLIDO_MATERNO,
    C.NOMBRE_CATEGORIA,
    NVL(COUNT(DISTINCT E.ID_PARTIDO), 0) AS PARTIDOS_JUGADOS,
    NVL(SUM(E.GOLES), 0) AS GOLES,
    NVL(SUM(E.ASISTENCIAS), 0) AS ASISTENCIAS,
    NVL(ROUND(AVG(E.PASES_EXITOSOS), 2), 0) AS PROMEDIO_PASES_EXITOSOS,
    NVL(ROUND(AVG(E.ENTRADAS_EXITOSAS), 2), 0) AS PROMEDIO_ENTRADAS_EXITOSAS,
    NVL(ROUND(AVG(E.MINUTOS_JUGADOS), 2), 0) AS PROMEDIO_MINUTOS
FROM FIDE_JUGADORES_TB J
LEFT JOIN FIDE_CATEGORIAS_TB C ON C.ID_CATEGORIA = J.ID_CATEGORIA
LEFT JOIN FIDE_ESTADISTICA_JUGADOR_TB E
    ON E.ID_JUGADOR = J.ID_JUGADOR
   AND E.ID_ESTADO = 1
WHERE J.ID_ESTADO = 1
GROUP BY J.ID_JUGADOR, J.CEDULA, J.NOMBRE, J.APELLIDO_PATERNO,
         J.APELLIDO_MATERNO, C.NOMBRE_CATEGORIA;

CREATE OR REPLACE FORCE VIEW FIDE_JUGADORES_PERFIL_CONSULTA_V AS
SELECT
    B.ID_JUGADOR,
    B.CEDULA,
    B.ID_CATEGORIA,
    B.NOMBRE_CATEGORIA,
    B.NOMBRE,
    B.APELLIDO_PATERNO,
    B.APELLIDO_MATERNO,
    B.DORSAL,
    B.ID_ESTADO,
    J.FECHA_NACIMIENTO,
    B.POSICIONES,
    NVL(S.GOLES, 0) AS GOLES,
    NVL(S.ASISTENCIAS, 0) AS ASISTENCIAS,
    NVL(S.PASES_TOTALES, 0) AS PASES_TOTALES,
    NVL(S.PASES_EXITOSOS_TOTALES, 0) AS PASES_EXITOSOS_TOTALES,
    NVL(S.REGATES_TOTALES, 0) AS REGATES_TOTALES,
    NVL(S.REGATES_EXITOSOS_TOTALES, 0) AS REGATES_EXITOSOS_TOTALES,
    NVL(S.TIROS_TOTALES, 0) AS TIROS_TOTALES,
    NVL(S.TIROS_EXITOSOS_TOTALES, 0) AS TIROS_EXITOSOS_TOTALES,
    NVL(S.ENTRADAS_TOTALES, 0) AS ENTRADAS_TOTALES,
    NVL(S.ENTRADAS_EXITOSAS_TOTALES, 0) AS ENTRADAS_EXITOSAS_TOTALES,
    NVL(S.MINUTOS_TOTALES, 0) AS MINUTOS_TOTALES,
    NVL(S.PROMEDIO_PASES_EXITOSOS, 0) AS PROMEDIO_PASES_EXITOSOS,
    NVL(S.PROMEDIO_REGATES_EXITOSOS, 0) AS PROMEDIO_REGATES_EXITOSOS,
    NVL(S.PROMEDIO_TIROS_EXITOSOS, 0) AS PROMEDIO_TIROS_EXITOSOS,
    NVL(S.PROMEDIO_ENTRADAS_EXITOSAS, 0) AS PROMEDIO_ENTRADAS_EXITOSAS,
    NVL(S.PROMEDIO_MINUTOS, 0) AS PROMEDIO_MINUTOS,
    NVL(T.TARJETAS, 0) AS TARJETAS,
    NVL(T.TARJETAS_AMARILLAS, 0) AS TARJETAS_AMARILLAS,
    NVL(T.TARJETAS_ROJAS, 0) AS TARJETAS_ROJAS,
    NVL(A.PARTIDOS_GANADOS, 0) AS PARTIDOS_GANADOS,
    NVL(A.PARTIDOS_PERDIDOS, 0) AS PARTIDOS_PERDIDOS,
    B.PARTIDOS_JUGADOS,
    B.LESIONES,
    FIDE_PROYECTOFINALACADEMIALEIVA_PCK.FIDE_FACTURACION_TB_MONTO_PAGADO_JUGADOR_FN(B.ID_JUGADOR) AS MONTO_PAGADO
FROM FIDE_JUGADORES_BUSQUEDA_CONSULTA_V B
JOIN FIDE_JUGADORES_TB J ON J.ID_JUGADOR = B.ID_JUGADOR
LEFT JOIN (
    SELECT E.ID_JUGADOR,
           SUM(E.GOLES) AS GOLES,
           SUM(E.ASISTENCIAS) AS ASISTENCIAS,
           SUM(E.PASES) AS PASES_TOTALES,
           SUM(E.PASES_EXITOSOS) AS PASES_EXITOSOS_TOTALES,
           SUM(E.REGATES) AS REGATES_TOTALES,
           SUM(E.REGATES_EXITOSOS) AS REGATES_EXITOSOS_TOTALES,
           SUM(E.TIROS) AS TIROS_TOTALES,
           SUM(E.TIROS_EXITOSOS) AS TIROS_EXITOSOS_TOTALES,
           SUM(E.ENTRADAS) AS ENTRADAS_TOTALES,
           SUM(E.ENTRADAS_EXITOSAS) AS ENTRADAS_EXITOSAS_TOTALES,
           SUM(E.MINUTOS_JUGADOS) AS MINUTOS_TOTALES,
           ROUND(AVG(E.PASES_EXITOSOS), 2) AS PROMEDIO_PASES_EXITOSOS,
           ROUND(AVG(E.REGATES_EXITOSOS), 2) AS PROMEDIO_REGATES_EXITOSOS,
           ROUND(AVG(E.TIROS_EXITOSOS), 2) AS PROMEDIO_TIROS_EXITOSOS,
           ROUND(AVG(E.ENTRADAS_EXITOSAS), 2) AS PROMEDIO_ENTRADAS_EXITOSAS,
           ROUND(AVG(E.MINUTOS_JUGADOS), 2) AS PROMEDIO_MINUTOS
    FROM FIDE_ESTADISTICA_JUGADOR_TB E
    WHERE E.ID_ESTADO = 1
    GROUP BY E.ID_JUGADOR
) S ON S.ID_JUGADOR = B.ID_JUGADOR
LEFT JOIN (
    SELECT CT.ID_JUGADOR,
           SUM(CT.CANTIDAD_TARJETAS) AS TARJETAS,
           SUM(CASE WHEN UPPER(TT.COLOR) LIKE '%AMARILL%' THEN CT.CANTIDAD_TARJETAS ELSE 0 END) AS TARJETAS_AMARILLAS,
           SUM(CASE WHEN UPPER(TT.COLOR) LIKE '%ROJ%' THEN CT.CANTIDAD_TARJETAS ELSE 0 END) AS TARJETAS_ROJAS
    FROM FIDE_TARJETAS_TB CT
    JOIN FIDE_TIPOTARJETAS_TB TT ON TT.ID_TIPOTARJETA = CT.ID_TIPOTARJETA
    WHERE CT.ID_ESTADO = 1
    GROUP BY CT.ID_JUGADOR
) T ON T.ID_JUGADOR = B.ID_JUGADOR
LEFT JOIN (
    SELECT A.ID_JUGADOR,
           SUM(CASE WHEN P.GOLES_FAVOR > P.GOLES_CONTRA THEN 1 ELSE 0 END) AS PARTIDOS_GANADOS,
           SUM(CASE WHEN P.GOLES_FAVOR < P.GOLES_CONTRA THEN 1 ELSE 0 END) AS PARTIDOS_PERDIDOS
    FROM FIDE_ASISTENCIA_TB A
    JOIN FIDE_PARTIDOS_TB P ON P.ID_PARTIDO = A.ID_PARTIDO
    WHERE A.ID_ESTADO = 1
      AND P.ID_ESTADO = 1
    GROUP BY A.ID_JUGADOR
) A ON A.ID_JUGADOR = B.ID_JUGADOR;

CREATE OR REPLACE FORCE VIEW FIDE_PARTIDOS_RESUMEN_CONSULTA_V AS
SELECT
    P.ID_PARTIDO,
    P.ID_CATEGORIA,
    C.NOMBRE_CATEGORIA,
    P.ID_TEMPORADA,
    T.TIPO_TEMPORADA,
    T.ANIO AS TEMPORADA_ANIO,
    P.FECHA,
    P.RIVAL,
    P.GOLES_FAVOR,
    P.GOLES_CONTRA,
    CASE WHEN P.GOLES_FAVOR > P.GOLES_CONTRA THEN 'ganado'
         WHEN P.GOLES_FAVOR < P.GOLES_CONTRA THEN 'perdido'
         ELSE 'empate' END AS RESULTADO,
    NVL(E.TIROS, 0) AS TIROS,
    NVL(E.TIROS_PORTERIA, 0) AS TIROS_PORTERIA,
    NVL(E.PASES_EXITOSOS, 0) AS PASES_EXITOSOS,
    NVL(E.PASES_FALLIDOS, 0) AS PASES_FALLIDOS,
    NVL(E.POSESION_BALON, 0) AS POSESION_BALON,
    NVL(A.TOTAL_ASISTENCIA, 0) AS TOTAL_ASISTENCIA,
    P.ID_ESTADO
FROM FIDE_PARTIDOS_TB P
LEFT JOIN FIDE_CATEGORIAS_TB C ON C.ID_CATEGORIA = P.ID_CATEGORIA
LEFT JOIN FIDE_TEMPORADAS_TB T ON T.ID_TEMPORADA = P.ID_TEMPORADA
LEFT JOIN (
    SELECT ID_PARTIDO,
           SUM(TIROS) AS TIROS,
           SUM(TIROS_PORTERIA) AS TIROS_PORTERIA,
           SUM(PASES_EXITOSOS) AS PASES_EXITOSOS,
           SUM(PASES_FALLIDOS) AS PASES_FALLIDOS,
           MAX(POSESION_BALON) AS POSESION_BALON
    FROM FIDE_ESTADISTICA_EQUIPO_TB
    WHERE ID_ESTADO = 1
    GROUP BY ID_PARTIDO
) E ON E.ID_PARTIDO = P.ID_PARTIDO
LEFT JOIN (
    SELECT ID_PARTIDO, COUNT(*) AS TOTAL_ASISTENCIA
    FROM FIDE_ASISTENCIA_TB
    WHERE ID_ESTADO = 1
    GROUP BY ID_PARTIDO
) A ON A.ID_PARTIDO = P.ID_PARTIDO;

CREATE OR REPLACE FORCE VIEW FIDE_PARTICIPACION_CONSULTA_V AS
SELECT
    A.ID_JUGADOR,
    A.ID_PARTIDO,
    J.NOMBRE,
    J.APELLIDO_PATERNO,
    J.APELLIDO_MATERNO,
    C.NOMBRE_CATEGORIA,
    P.FECHA,
    P.RIVAL,
    P.GOLES_FAVOR,
    P.GOLES_CONTRA,
    CASE WHEN P.GOLES_FAVOR > P.GOLES_CONTRA THEN 'ganado'
         WHEN P.GOLES_FAVOR < P.GOLES_CONTRA THEN 'perdido'
         ELSE 'empate' END AS RESULTADO,
    NVL(E.PASES, 0) AS PASES,
    NVL(E.PASES_EXITOSOS, 0) AS PASES_EXITOSOS,
    NVL(E.REGATES, 0) AS REGATES,
    NVL(E.REGATES_EXITOSOS, 0) AS REGATES_EXITOSOS,
    NVL(E.TIROS, 0) AS TIROS,
    NVL(E.TIROS_EXITOSOS, 0) AS TIROS_EXITOSOS,
    NVL(E.ENTRADAS, 0) AS ENTRADAS,
    NVL(E.ENTRADAS_EXITOSAS, 0) AS ENTRADAS_EXITOSAS,
    NVL(E.MINUTOS_JUGADOS, 0) AS MINUTOS_JUGADOS,
    NVL(E.GOLES, 0) AS GOLES,
    NVL(E.ASISTENCIAS, 0) AS ASISTENCIAS,
    NVL(POS.POSICIONES, 'Sin posicion') AS POSICIONES
FROM FIDE_ASISTENCIA_TB A
JOIN FIDE_JUGADORES_TB J ON J.ID_JUGADOR = A.ID_JUGADOR
JOIN FIDE_PARTIDOS_TB P ON P.ID_PARTIDO = A.ID_PARTIDO
LEFT JOIN FIDE_CATEGORIAS_TB C ON C.ID_CATEGORIA = P.ID_CATEGORIA
LEFT JOIN FIDE_ESTADISTICA_JUGADOR_TB E
    ON E.ID_JUGADOR = A.ID_JUGADOR
   AND E.ID_PARTIDO = A.ID_PARTIDO
   AND E.ID_ESTADO = 1
LEFT JOIN (
    SELECT JP.ID_JUGADOR,
           LISTAGG(PS.NOMBRE_POSICION, ', ') WITHIN GROUP (ORDER BY PS.NOMBRE_POSICION) AS POSICIONES
    FROM FIDE_JUGADOR_POSICIONES_TB JP
    JOIN FIDE_POSICIONES_TB PS ON PS.ID_POSICION = JP.ID_POSICION
    WHERE JP.ID_ESTADO = 1
      AND PS.ID_ESTADO = 1
    GROUP BY JP.ID_JUGADOR
) POS ON POS.ID_JUGADOR = A.ID_JUGADOR
WHERE A.ID_ESTADO = 1
  AND J.ID_ESTADO = 1
  AND P.ID_ESTADO = 1;

CREATE OR REPLACE FORCE VIEW FIDE_DISPONIBILIDAD_CONSULTA_V AS
SELECT
    J.ID_JUGADOR,
    J.ID_CATEGORIA,
    J.NOMBRE || ' ' || J.APELLIDO_PATERNO || ' ' || J.APELLIDO_MATERNO AS NOMBRE_COMPLETO,
    C.NOMBRE_CATEGORIA,
    NVL(L.LESIONES_ACTIVAS, 0) AS LESIONES,
    NVL(T.TARJETAS_AMARILLAS, 0) AS TARJETAS_AMARILLAS,
    NVL(T.TARJETAS_ROJAS, 0) AS TARJETAS_ROJAS,
    CASE WHEN NVL(L.LESIONES_ACTIVAS, 0) > 0 THEN 'LESIONADO'
         WHEN NVL(T.TARJETAS_ROJAS, 0) > 0 THEN 'SUSPENDIDO'
         ELSE 'DISPONIBLE' END AS ESTADO
FROM FIDE_JUGADORES_TB J
LEFT JOIN FIDE_CATEGORIAS_TB C ON C.ID_CATEGORIA = J.ID_CATEGORIA
LEFT JOIN (
    SELECT PM.ID_JUGADOR, COUNT(DISTINCT L.ID_LESION) AS LESIONES_ACTIVAS
    FROM FIDE_PARTE_MEDICO_TB PM
    JOIN FIDE_LESIONES_TB L ON L.ID_PARTEMEDICO = PM.ID_PARTEMEDICO
    WHERE PM.ID_ESTADO = 1
      AND L.ID_ESTADO = 1
      AND (L.FECHA_RECUPERACION IS NULL OR L.FECHA_RECUPERACION >= TRUNC(SYSDATE))
    GROUP BY PM.ID_JUGADOR
) L ON L.ID_JUGADOR = J.ID_JUGADOR
LEFT JOIN (
    SELECT CT.ID_JUGADOR,
           SUM(CASE WHEN UPPER(TT.COLOR) LIKE '%AMARILL%' THEN CT.CANTIDAD_TARJETAS ELSE 0 END) AS TARJETAS_AMARILLAS,
           SUM(CASE WHEN UPPER(TT.COLOR) LIKE '%ROJ%' THEN CT.CANTIDAD_TARJETAS ELSE 0 END) AS TARJETAS_ROJAS
    FROM FIDE_TARJETAS_TB CT
    JOIN FIDE_TIPOTARJETAS_TB TT ON TT.ID_TIPOTARJETA = CT.ID_TIPOTARJETA
    WHERE CT.ID_ESTADO = 1
    GROUP BY CT.ID_JUGADOR
) T ON T.ID_JUGADOR = J.ID_JUGADOR
WHERE J.ID_ESTADO = 1;

CREATE OR REPLACE FORCE VIEW FIDE_JUGADOR_LESIONES_CONSULTA_V AS
SELECT
    PM.ID_JUGADOR,
    J.NOMBRE || ' ' || J.APELLIDO_PATERNO || ' ' || J.APELLIDO_MATERNO AS NOMBRE_COMPLETO,
    PM.FECHA,
    L.DESCRIPCION,
    PM.OBSERVACIONES,
    L.FECHA_RECUPERACION,
    CASE WHEN L.FECHA_RECUPERACION IS NULL OR L.FECHA_RECUPERACION >= TRUNC(SYSDATE) THEN 'ACTIVA'
         ELSE 'RECUPERADA' END AS ESTADO
FROM FIDE_PARTE_MEDICO_TB PM
JOIN FIDE_LESIONES_TB L ON L.ID_PARTEMEDICO = PM.ID_PARTEMEDICO
JOIN FIDE_JUGADORES_TB J ON J.ID_JUGADOR = PM.ID_JUGADOR
WHERE PM.ID_ESTADO = 1
  AND L.ID_ESTADO = 1;

