PROCEDURE FIDE_JSON_INICIAR(P_JSON OUT CLOB) IS
BEGIN
    DBMS_LOB.CREATETEMPORARY(P_JSON, TRUE);
    DBMS_LOB.WRITEAPPEND(P_JSON, 1, '[');
END FIDE_JSON_INICIAR;

PROCEDURE FIDE_JSON_AGREGAR(
    P_JSON IN OUT NOCOPY CLOB,
    P_ITEM IN CLOB,
    P_PRIMER_ITEM IN OUT BOOLEAN
) IS
BEGIN
    IF NOT P_PRIMER_ITEM THEN
        DBMS_LOB.WRITEAPPEND(P_JSON, 1, ',');
    END IF;

    DBMS_LOB.APPEND(P_JSON, P_ITEM);
    P_PRIMER_ITEM := FALSE;
END FIDE_JSON_AGREGAR;

PROCEDURE FIDE_JSON_CERRAR(P_JSON IN OUT NOCOPY CLOB) IS
BEGIN
    DBMS_LOB.WRITEAPPEND(P_JSON, 1, ']');
END FIDE_JSON_CERRAR;

FUNCTION FIDE_CONSULTAS_TEMPORADAS_LISTAR_FN RETURN CLOB
IS
    V_JSON CLOB;
    V_PRIMER_ITEM BOOLEAN := TRUE;

    CURSOR C_DATOS IS
        SELECT JSON_OBJECT(
            'ID_TEMPORADA' VALUE ID_TEMPORADA,
            'TIPO_TEMPORADA' VALUE TIPO_TEMPORADA,
            'ANIO' VALUE ANIO RETURNING CLOB
        ) AS ITEM
        FROM FIDE_TEMPORADAS_V
        WHERE ID_ESTADO = 1
        ORDER BY ANIO DESC;
BEGIN
    FIDE_JSON_INICIAR(V_JSON);
    FOR DATO IN C_DATOS LOOP
        FIDE_JSON_AGREGAR(V_JSON, DATO.ITEM, V_PRIMER_ITEM);
    END LOOP;
    FIDE_JSON_CERRAR(V_JSON);
    RETURN V_JSON;
EXCEPTION
    WHEN OTHERS THEN RETURN TO_CLOB('[]');
END FIDE_CONSULTAS_TEMPORADAS_LISTAR_FN;

