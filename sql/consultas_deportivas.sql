CREATE OR REPLACE FORCE VIEW FIDE_JUGADORES_CONSULTA_V AS
SELECT
    J.ID_JUGADOR,
    J.CEDULA,
    J.ID_CATEGORIA,
    C.NOMBRE_CATEGORIA,
    J.NOMBRE,
    J.APELLIDO_PATERNO,
    J.APELLIDO_MATERNO,
    J.DORSAL,
    J.FECHA_NACIMIENTO,
    J.ID_ESTADO,
    J.ID_DIRECCION_EXACTA
FROM FIDE_JUGADORES_TB J
LEFT JOIN FIDE_CATEGORIAS_TB C ON C.ID_CATEGORIA = J.ID_CATEGORIA;

CREATE OR REPLACE FORCE VIEW FIDE_JUGADOR_POSICIONES_CONSULTA_V AS
SELECT
    JP.ID_JUGADOR,
    JP.ID_POSICION,
    P.NOMBRE_POSICION
FROM FIDE_JUGADOR_POSICIONES_TB JP
JOIN FIDE_POSICIONES_TB P ON P.ID_POSICION = JP.ID_POSICION
WHERE JP.ID_ESTADO = 1
  AND P.ID_ESTADO = 1;

CREATE OR REPLACE FORCE VIEW FIDE_ESTADISTICA_JUGADOR_CONSULTA_V AS
SELECT
    E.ID_JUGADOR,
    E.ID_PARTIDO,
    P.ID_TEMPORADA,
    E.PASES,
    E.PASES_EXITOSOS,
    E.REGATES,
    E.REGATES_EXITOSOS,
    E.TIROS,
    E.TIROS_EXITOSOS,
    E.ENTRADAS,
    E.ENTRADAS_EXITOSAS,
    E.MINUTOS_JUGADOS,
    E.GOLES,
    E.ASISTENCIAS
FROM FIDE_ESTADISTICA_JUGADOR_TB E
LEFT JOIN FIDE_PARTIDOS_TB P ON P.ID_PARTIDO = E.ID_PARTIDO
WHERE E.ID_ESTADO = 1;

