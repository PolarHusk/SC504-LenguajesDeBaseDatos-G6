        'TOP_GOLEADOR_GOLES' VALUE (SELECT GOLES FROM (SELECT SUM(E.GOLES) GOLES FROM FIDE_ESTADISTICA_JUGADOR_TB E JOIN FIDE_PARTIDOS_TB P ON P.ID_PARTIDO=E.ID_PARTIDO WHERE E.ID_ESTADO IN (1, 4) AND (P_TEMPORADA IS NULL OR P.ID_TEMPORADA=P_TEMPORADA) AND (P_CATEGORIA IS NULL OR P.ID_CATEGORIA=P_CATEGORIA) GROUP BY E.ID_JUGADOR ORDER BY GOLES DESC) WHERE ROWNUM=1),
        'TOP_ASISTENTE_NOMBRE' VALUE (SELECT NOMBRE_COMPLETO FROM (SELECT J.NOMBRE || ' ' || J.APELLIDO_PATERNO AS NOMBRE_COMPLETO, SUM(E.ASISTENCIAS) ASISTENCIAS FROM FIDE_ESTADISTICA_JUGADOR_TB E JOIN FIDE_JUGADORES_TB J ON J.ID_JUGADOR=E.ID_JUGADOR JOIN FIDE_PARTIDOS_TB P ON P.ID_PARTIDO=E.ID_PARTIDO WHERE E.ID_ESTADO IN (1, 4) AND (P_TEMPORADA IS NULL OR P.ID_TEMPORADA=P_TEMPORADA) AND (P_CATEGORIA IS NULL OR P.ID_CATEGORIA=P_CATEGORIA) GROUP BY J.NOMBRE,J.APELLIDO_PATERNO ORDER BY ASISTENCIAS DESC) WHERE ROWNUM=1),
