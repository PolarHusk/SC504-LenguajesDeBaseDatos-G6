        'TOTAL_LESIONES' VALUE (SELECT COUNT(*) FROM FIDE_LESIONES_TB L JOIN FIDE_PARTE_MEDICO_TB PM ON PM.ID_PARTEMEDICO=L.ID_PARTEMEDICO JOIN FIDE_JUGADORES_TB J ON J.ID_JUGADOR=PM.ID_JUGADOR WHERE L.ID_ESTADO=1 AND (P_CATEGORIA IS NULL OR J.ID_CATEGORIA=P_CATEGORIA)),
