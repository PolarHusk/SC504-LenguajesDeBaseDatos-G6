        'PASES' VALUE E.PASES, 'PASES_EXITOSOS' VALUE E.PASES_EXITOSOS,
        'REGATES' VALUE E.REGATES, 'REGATES_EXITOSOS' VALUE E.REGATES_EXITOSOS, 'TIROS' VALUE E.TIROS, 'TIROS_EXITOSOS' VALUE E.TIROS_EXITOSOS,
        'ENTRADAS' VALUE E.ENTRADAS, 'ENTRADAS_EXITOSAS' VALUE E.ENTRADAS_EXITOSAS, 'MINUTOS_JUGADOS' VALUE E.MINUTOS_JUGADOS, 'GOLES' VALUE E.GOLES, 'ASISTENCIAS' VALUE E.ASISTENCIAS) RETURNING CLOB), TO_CLOB('[]')) INTO V_RESULTADO
    FROM FIDE_ESTADISTICA_JUGADOR_TB E
    JOIN FIDE_JUGADORES_TB J ON J.ID_JUGADOR = E.ID_JUGADOR
    JOIN FIDE_PARTIDOS_TB P ON P.ID_PARTIDO = E.ID_PARTIDO
    JOIN FIDE_CATEGORIAS_TB C ON C.ID_CATEGORIA = P.ID_CATEGORIA
    WHERE E.ID_JUGADOR=P_JUGADOR AND E.ID_PARTIDO=P_PARTIDO AND E.ID_ESTADO IN (1, 4);
    RETURN V_RESULTADO;
END FIDE_CONSULTAS_JUGADOR_PARTIDO_FN;

FUNCTION FIDE_CONSULTAS_DISPONIBILIDAD_FN(P_CATEGORIA NUMBER) RETURN CLOB IS V_RESULTADO CLOB;
BEGIN
    SELECT COALESCE(JSON_ARRAYAGG(JSON_OBJECT('ID_JUGADOR' VALUE J.ID_JUGADOR, 'NOMBRE_COMPLETO' VALUE J.NOMBRE || ' ' || J.APELLIDO_PATERNO || ' ' || J.APELLIDO_MATERNO,
        'NOMBRE_CATEGORIA' VALUE J.CATEGORIA, 'LESIONES' VALUE (SELECT COUNT(*) FROM FIDE_LESIONES_V L JOIN FIDE_PARTE_MEDICO_TB PM ON PM.ID_PARTEMEDICO=L.ID_PARTEMEDICO WHERE PM.ID_JUGADOR=J.ID_JUGADOR AND L.ID_ESTADO=1),
        'TARJETAS_AMARILLAS' VALUE 0, 'TARJETAS_ROJAS' VALUE 0, 'ESTADO' VALUE J.ESTADO) RETURNING CLOB), TO_CLOB('[]')) INTO V_RESULTADO
    FROM FIDE_JUGADORES_V J WHERE J.ID_ESTADO=1 AND (P_CATEGORIA IS NULL OR J.ID_CATEGORIA=P_CATEGORIA);
    RETURN V_RESULTADO;
END FIDE_CONSULTAS_DISPONIBILIDAD_FN;

FUNCTION FIDE_CONSULTAS_JUGADOR_LESIONES_FN(P_JUGADOR NUMBER) RETURN CLOB IS V_RESULTADO CLOB;
BEGIN
    SELECT COALESCE(JSON_ARRAYAGG(JSON_OBJECT('ID_LESION' VALUE L.ID_LESION, 'NOMBRE_TIPO_LESION' VALUE L.TIPO_LESION, 'DESCRIPCION' VALUE L.DESCRIPCION,
        'FECHA_PARTE_MEDICO' VALUE TO_CHAR(PM.FECHA,'YYYY-MM-DD'), 'FECHA_RECUPERACION' VALUE TO_CHAR(L.FECHA_RECUPERACION,'YYYY-MM-DD'), 'MEDICO' VALUE M.NOMBRE || ' ' || M.APELLIDO_PATERNO) RETURNING CLOB), TO_CLOB('[]')) INTO V_RESULTADO
    FROM FIDE_LESIONES_V L
    JOIN FIDE_PARTE_MEDICO_TB PM ON PM.ID_PARTEMEDICO=L.ID_PARTEMEDICO
    JOIN FIDE_MEDICOS_TB M ON M.ID_MEDICO=PM.ID_MEDICO
    WHERE PM.ID_JUGADOR=P_JUGADOR AND L.ID_ESTADO=1;
    RETURN V_RESULTADO;
END FIDE_CONSULTAS_JUGADOR_LESIONES_FN;

FUNCTION FIDE_CONSULTAS_JUGADOR_PARTIDOS_FN(P_JUGADOR NUMBER) RETURN CLOB IS V_RESULTADO CLOB;
BEGIN
    SELECT COALESCE(JSON_ARRAYAGG(JSON_OBJECT('ID_PARTIDO' VALUE P.ID_PARTIDO, 'FECHA' VALUE TO_CHAR(P.FECHA,'YYYY-MM-DD'), 'RIVAL' VALUE P.RIVAL,
        'GOLES_FAVOR' VALUE P.GOLES_FAVOR, 'GOLES_CONTRA' VALUE P.GOLES_CONTRA, 'RESULTADO' VALUE CASE WHEN P.GOLES_FAVOR>P.GOLES_CONTRA THEN 'Victoria' WHEN P.GOLES_FAVOR<P.GOLES_CONTRA THEN 'Derrota' ELSE 'Empate' END,
        'MINUTOS_JUGADOS' VALUE E.MINUTOS_JUGADOS, 'GOLES' VALUE E.GOLES, 'ASISTENCIAS' VALUE E.ASISTENCIAS) RETURNING CLOB), TO_CLOB('[]')) INTO V_RESULTADO
    FROM FIDE_ESTADISTICA_JUGADOR_TB E JOIN FIDE_PARTIDOS_TB P ON P.ID_PARTIDO=E.ID_PARTIDO WHERE E.ID_JUGADOR=P_JUGADOR AND E.ID_ESTADO IN (1, 4) AND P.ID_ESTADO IN (1, 4);
    RETURN V_RESULTADO;
END FIDE_CONSULTAS_JUGADOR_PARTIDOS_FN;
