FUNCTION FIDE_CONSULTAS_PARTIDOS_BUSCAR_FN(P_ANIO NUMBER, P_TEMPORADA NUMBER, P_RIVAL VARCHAR2, P_FECHA VARCHAR2, P_RESULTADO VARCHAR2) RETURN CLOB IS V_RESULTADO CLOB;
BEGIN
    SELECT COALESCE(JSON_ARRAYAGG(JSON_OBJECT(
        'ID_PARTIDO' VALUE ID_PARTIDO, 'FECHA' VALUE TO_CHAR(FECHA, 'YYYY-MM-DD'), 'RIVAL' VALUE RIVAL,
        'GOLES_FAVOR' VALUE GOLES_FAVOR, 'GOLES_CONTRA' VALUE GOLES_CONTRA, 'RESULTADO' VALUE RESULTADO,
        'TIPO_TEMPORADA' VALUE TIPO_TEMPORADA, 'TEMPORADA_ANIO' VALUE ANIO,
        'TOTAL_ASISTENCIA' VALUE TOTAL_ASISTENCIA) RETURNING CLOB), TO_CLOB('[]')) INTO V_RESULTADO
    FROM (
        SELECT P.*, T.TIPO_TEMPORADA, T.ANIO,
            CASE WHEN P.GOLES_FAVOR > P.GOLES_CONTRA THEN 'Victoria' WHEN P.GOLES_FAVOR < P.GOLES_CONTRA THEN 'Derrota' ELSE 'Empate' END AS RESULTADO,
            (SELECT COUNT(*) FROM FIDE_ASISTENCIA_TB A WHERE A.ID_PARTIDO = P.ID_PARTIDO AND A.ID_ESTADO IN (1, 4)) AS TOTAL_ASISTENCIA
        FROM FIDE_PARTIDOS_V P
        JOIN FIDE_TEMPORADAS_TB T ON T.ID_TEMPORADA = P.ID_TEMPORADA
        WHERE P.ID_ESTADO IN (1, 4)
          AND (P_ANIO IS NULL OR T.ANIO = P_ANIO)
          AND (P_TEMPORADA IS NULL OR P.ID_TEMPORADA = P_TEMPORADA)
          AND (P_RIVAL IS NULL OR UPPER(P.RIVAL) LIKE '%' || UPPER(P_RIVAL) || '%')
          AND (P_FECHA IS NULL OR TO_CHAR(P.FECHA, 'YYYY-MM-DD') = P_FECHA)
          AND (P_RESULTADO IS NULL OR LOWER(CASE WHEN P.GOLES_FAVOR > P.GOLES_CONTRA THEN 'Victoria' WHEN P.GOLES_FAVOR < P.GOLES_CONTRA THEN 'Derrota' ELSE 'Empate' END) = P_RESULTADO)
    );
    RETURN V_RESULTADO;
END FIDE_CONSULTAS_PARTIDOS_BUSCAR_FN;

FUNCTION FIDE_CONSULTAS_JUGADORES_BUSCAR_FN(P_NOMBRE VARCHAR2, P_CATEGORIA NUMBER, P_CEDULA VARCHAR2, P_POSICION NUMBER) RETURN CLOB IS V_RESULTADO CLOB;
BEGIN
    SELECT COALESCE(JSON_ARRAYAGG(JSON_OBJECT(
        'ID_JUGADOR' VALUE ID_JUGADOR, 'NOMBRE' VALUE NOMBRE, 'APELLIDO_PATERNO' VALUE APELLIDO_PATERNO,
        'APELLIDO_MATERNO' VALUE APELLIDO_MATERNO, 'CEDULA' VALUE CEDULA, 'DORSAL' VALUE DORSAL,
        'NOMBRE_CATEGORIA' VALUE CATEGORIA, 'POSICIONES' VALUE POSICIONES,
        'PARTIDOS_JUGADOS' VALUE PARTIDOS_JUGADOS, 'LESIONES' VALUE LESIONES) RETURNING CLOB), TO_CLOB('[]')) INTO V_RESULTADO
    FROM (
        SELECT J.*, JP.POSICIONES,
            (SELECT COUNT(*) FROM FIDE_ASISTENCIA_TB A WHERE A.ID_JUGADOR = J.ID_JUGADOR AND A.ID_ESTADO IN (1, 4)) PARTIDOS_JUGADOS,
            (SELECT COUNT(*) FROM FIDE_LESIONES_V L JOIN FIDE_PARTE_MEDICO_TB PM ON PM.ID_PARTEMEDICO = L.ID_PARTEMEDICO WHERE PM.ID_JUGADOR = J.ID_JUGADOR AND L.ID_ESTADO = 1) LESIONES
        FROM FIDE_JUGADORES_V J LEFT JOIN FIDE_JUGADOR_POSICIONES_V JP ON JP.ID_JUGADOR = J.ID_JUGADOR
        WHERE J.ID_ESTADO = 1
          AND (P_NOMBRE IS NULL OR UPPER(J.NOMBRE || ' ' || J.APELLIDO_PATERNO || ' ' || J.APELLIDO_MATERNO) LIKE '%' || UPPER(P_NOMBRE) || '%')
          AND (P_CATEGORIA IS NULL OR J.ID_CATEGORIA = P_CATEGORIA)
          AND (P_CEDULA IS NULL OR J.CEDULA LIKE '%' || P_CEDULA || '%')
          AND (P_POSICION IS NULL OR EXISTS (SELECT 1 FROM FIDE_JUGADOR_POSICIONES_TB X WHERE X.ID_JUGADOR = J.ID_JUGADOR AND X.ID_POSICION = P_POSICION AND X.ID_ESTADO = 1))
    );
    RETURN V_RESULTADO;
END FIDE_CONSULTAS_JUGADORES_BUSCAR_FN;

