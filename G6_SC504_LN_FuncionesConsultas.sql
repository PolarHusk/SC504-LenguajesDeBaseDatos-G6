BEGIN
    SELECT JSON_ARRAY(JSON_OBJECT(
        'TOTAL_JUGADORES' VALUE (SELECT COUNT(*) FROM FIDE_JUGADORES_TB J WHERE J.ID_ESTADO=1 AND (P_CATEGORIA IS NULL OR J.ID_CATEGORIA=P_CATEGORIA)),
