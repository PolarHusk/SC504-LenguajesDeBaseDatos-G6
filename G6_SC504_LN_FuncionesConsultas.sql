FUNCTION FIDE_JUGADORES_TB_VALIDAR_EDAD_CATEGORIA_FN(P_FECHA_NACIMIENTO DATE, P_ID_CATEGORIA NUMBER) RETURN NUMBER IS
    V_NOMBRE_CATEGORIA FIDE_CATEGORIAS_TB.NOMBRE_CATEGORIA%TYPE;
    V_EDAD NUMBER;
    V_EDAD_MINIMA NUMBER;
    V_EDAD_MAXIMA NUMBER;
BEGIN
    SELECT UPPER(NOMBRE_CATEGORIA) INTO V_NOMBRE_CATEGORIA
    FROM FIDE_CATEGORIAS_TB
    WHERE ID_CATEGORIA = P_ID_CATEGORIA;

    V_EDAD := TRUNC(MONTHS_BETWEEN(TRUNC(SYSDATE), P_FECHA_NACIMIENTO) / 12);
    IF V_NOMBRE_CATEGORIA = 'TERCERA DIVISION' THEN
        RETURN CASE WHEN V_EDAD >= 18 THEN 1 ELSE 0 END;
    END IF;

    IF NOT REGEXP_LIKE(V_NOMBRE_CATEGORIA, '^U-[0-9]+$') THEN
        RETURN 0;
    END IF;

    V_EDAD_MAXIMA := TO_NUMBER(REGEXP_SUBSTR(V_NOMBRE_CATEGORIA, '[0-9]+'));
    V_EDAD_MINIMA := CASE
        WHEN V_EDAD_MAXIMA = 5 THEN 0
        WHEN V_EDAD_MAXIMA = 20 THEN 18
        ELSE V_EDAD_MAXIMA - 1
    END;

    RETURN CASE WHEN V_EDAD BETWEEN V_EDAD_MINIMA AND V_EDAD_MAXIMA THEN 1 ELSE 0 END;
END FIDE_JUGADORES_TB_VALIDAR_EDAD_CATEGORIA_FN;

