FUNCTION FIDE_CONSULTAS_JUGADORES_COMPARAR_FN(P_JUGADOR_1 NUMBER, P_JUGADOR_2 NUMBER, P_JUGADOR_3 NUMBER) RETURN CLOB IS V_RESULTADO CLOB;
BEGIN
    SELECT COALESCE(JSON_ARRAYAGG(JSON_OBJECT('ID_JUGADOR' VALUE ID_JUGADOR, 'NOMBRE' VALUE NOMBRE, 'APELLIDO_PATERNO' VALUE APELLIDO_PATERNO, 'APELLIDO_MATERNO' VALUE APELLIDO_MATERNO, 'PARTIDOS_JUGADOS' VALUE PARTIDOS_JUGADOS, 'GOLES' VALUE GOLES, 'ASISTENCIAS' VALUE ASISTENCIAS, 'PROMEDIO_PASES_EXITOSOS' VALUE PROMEDIO_PASES_EXITOSOS, 'PROMEDIO_ENTRADAS_EXITOSAS' VALUE PROMEDIO_ENTRADAS_EXITOSAS, 'PROMEDIO_MINUTOS' VALUE PROMEDIO_MINUTOS) RETURNING CLOB), TO_CLOB('[]')) INTO V_RESULTADO
    FROM JSON_TABLE(FIDE_CONSULTAS_JUGADOR_RESUMEN_FN(P_JUGADOR_1), '$[*]' COLUMNS (ID_JUGADOR NUMBER PATH '$.ID_JUGADOR', NOMBRE VARCHAR2(100) PATH '$.NOMBRE', APELLIDO_PATERNO VARCHAR2(100) PATH '$.APELLIDO_PATERNO', APELLIDO_MATERNO VARCHAR2(100) PATH '$.APELLIDO_MATERNO', PARTIDOS_JUGADOS NUMBER PATH '$.PARTIDOS_JUGADOS', GOLES NUMBER PATH '$.GOLES', ASISTENCIAS NUMBER PATH '$.ASISTENCIAS', PROMEDIO_PASES_EXITOSOS NUMBER PATH '$.PROMEDIO_PASES_EXITOSOS', PROMEDIO_ENTRADAS_EXITOSAS NUMBER PATH '$.PROMEDIO_ENTRADAS_EXITOSAS', PROMEDIO_MINUTOS NUMBER PATH '$.PROMEDIO_MINUTOS'));
    -- Se agregan los otros jugadores reutilizando el mismo resumen.
    V_RESULTADO := '[' || SUBSTR(V_RESULTADO, 2, LENGTH(V_RESULTADO)-2) || ',' || SUBSTR(FIDE_CONSULTAS_JUGADOR_RESUMEN_FN(P_JUGADOR_2), 2, LENGTH(FIDE_CONSULTAS_JUGADOR_RESUMEN_FN(P_JUGADOR_2))-2) || ',' || SUBSTR(FIDE_CONSULTAS_JUGADOR_RESUMEN_FN(P_JUGADOR_3), 2, LENGTH(FIDE_CONSULTAS_JUGADOR_RESUMEN_FN(P_JUGADOR_3))-2) || ']';
    RETURN REPLACE(REPLACE(V_RESULTADO, '[,', '['), ',]', ']');
END FIDE_CONSULTAS_JUGADORES_COMPARAR_FN;

