/*Indica si el partido se gano, empato o perdio*/

FUNCTION RESULTADO_PARTIDO_FN(
	P_ID_PARTIDO IN FIDE_PARTIDOS_TB.ID_PARTIDO%TYPE
)
RETURN VARCHAR2
IS
	V_GOLES_FAVOR FIDE_PARTIDOS_TB.GOLES_FAVOR%TYPE;
	V_GOLES_CONTRA FIDE_PARTIDOS_TB.GOLES_CONTRA%TYPE;
	V_RESULTADO VARCHAR2(20);

	CURSOR C_PARTIDO IS
	SELECT GOLES_FAVOR, GOLES_CONTRA
	FROM FIDE_PARTIDOS_TB
	WHERE ID_PARTIDO = P_ID_PARTIDO;

BEGIN
	OPEN C_PARTIDO;
	FETCH C_PARTIDO INTO V_GOLES_FAVOR, V_GOLES_CONTRA;

	IF C_PARTIDO%FOUND THEN
		IF V_GOLES_FAVOR > V_GOLES_CONTRA THEN
			V_RESULTADO := 'GANADO';
		ELSIF V_GOLES_FAVOR < V_GOLES_CONTRA THEN
			V_RESULTADO := 'PERDIDO';
		ELSE
			V_RESULTADO := 'EMPATE';
		END IF;
	ELSE
		V_RESULTADO := 'NO ENCONTRADO';
	END IF;

	CLOSE C_PARTIDO;

	RETURN V_RESULTADO;

END RESULTADO_PARTIDO_FN;



