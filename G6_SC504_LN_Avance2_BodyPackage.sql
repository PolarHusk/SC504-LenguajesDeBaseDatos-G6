	V_TOTAL_LESIONES NUMBER;

	CURSOR C_LESIONES IS /*Cuenta en colaboracion a parte medico y a lesiones*/
	SELECT COUNT(*)
	FROM FIDE_PARTE_MEDICO_TB PM
	INNER JOIN FIDE_LESIONES_TB L
	ON PM.ID_PARTEMEDICO = L.ID_PARTEMEDICO
	WHERE PM.ID_JUGADOR = P_ID_JUGADOR
	AND L.ID_ESTADO = 1;

BEGIN
	OPEN C_LESIONES;
	FETCH C_LESIONES INTO V_TOTAL_LESIONES;
	CLOSE C_LESIONES;

	RETURN V_TOTAL_LESIONES;

END TOTAL_LESIONES_JUGADOR_FN;



/*Calcula el promedio de minutos jugados de un jugador*/

FUNCTION PROMEDIO_MINUTOS_JUGADOR_FN(
	P_ID_JUGADOR IN FIDE_ESTADISTICA_JUGADOR_TB.ID_JUGADOR%TYPE
)
RETURN NUMBER
IS
	V_PROMEDIO_MINUTOS NUMBER;

	CURSOR C_MINUTOS IS
	SELECT NVL(AVG(MINUTOS_JUGADOS), 0)
	FROM FIDE_ESTADISTICA_JUGADOR_TB
	WHERE ID_JUGADOR = P_ID_JUGADOR;

BEGIN
	OPEN C_MINUTOS;
	FETCH C_MINUTOS INTO V_PROMEDIO_MINUTOS;
	CLOSE C_MINUTOS;

	RETURN V_PROMEDIO_MINUTOS;

END PROMEDIO_MINUTOS_JUGADOR_FN;