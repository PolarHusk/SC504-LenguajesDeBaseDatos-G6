CREATE OR REPLACE TRIGGER FIDE_ASISTENCIA_VALIDAR_JUGADOR_TRG
BEFORE INSERT OR UPDATE OF ID_PARTIDO, ID_JUGADOR, ID_ESTADO ON FIDE_ASISTENCIA_TB
FOR EACH ROW
DECLARE
    V_CATEGORIA_JUGADOR NUMBER;
    V_CATEGORIA_PARTIDO NUMBER;
    V_ESTADO_JUGADOR NUMBER;
BEGIN
    SELECT ID_CATEGORIA, ID_ESTADO INTO V_CATEGORIA_JUGADOR, V_ESTADO_JUGADOR FROM FIDE_JUGADORES_TB WHERE ID_JUGADOR = :NEW.ID_JUGADOR;
    SELECT ID_CATEGORIA INTO V_CATEGORIA_PARTIDO FROM FIDE_PARTIDOS_TB WHERE ID_PARTIDO = :NEW.ID_PARTIDO;
    IF V_ESTADO_JUGADOR <> 1 OR V_CATEGORIA_JUGADOR <> V_CATEGORIA_PARTIDO THEN
        RAISE_APPLICATION_ERROR(-20002, 'El jugador debe estar activo y pertenecer a la categoria del partido.');
    END IF;
END FIDE_ASISTENCIA_VALIDAR_JUGADOR_TRG;
