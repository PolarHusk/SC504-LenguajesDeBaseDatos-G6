CREATE OR REPLACE TRIGGER FIDE_ESTADISTICA_JUGADOR_VALIDAR_TRG
BEFORE INSERT OR UPDATE OF ID_JUGADOR, ID_PARTIDO, PASES, PASES_EXITOSOS, REGATES, REGATES_EXITOSOS, TIROS, TIROS_EXITOSOS, ENTRADAS, ENTRADAS_EXITOSAS, ID_ESTADO ON FIDE_ESTADISTICA_JUGADOR_TB
FOR EACH ROW
DECLARE
    V_CATEGORIA_JUGADOR NUMBER;
    V_CATEGORIA_PARTIDO NUMBER;
    V_ESTADO_JUGADOR NUMBER;
    V_ESTADO_PARTIDO NUMBER;
    V_ASISTIO NUMBER;
BEGIN
    IF NVL(:NEW.PASES_EXITOSOS, 0) > NVL(:NEW.PASES, 0) OR NVL(:NEW.REGATES_EXITOSOS, 0) > NVL(:NEW.REGATES, 0) OR NVL(:NEW.TIROS_EXITOSOS, 0) > NVL(:NEW.TIROS, 0) OR NVL(:NEW.ENTRADAS_EXITOSAS, 0) > NVL(:NEW.ENTRADAS, 0) THEN
        RAISE_APPLICATION_ERROR(-20003, 'Las acciones exitosas no pueden superar las acciones totales.');
    END IF;
    SELECT ID_CATEGORIA, ID_ESTADO INTO V_CATEGORIA_JUGADOR, V_ESTADO_JUGADOR FROM FIDE_JUGADORES_TB WHERE ID_JUGADOR = :NEW.ID_JUGADOR;
    SELECT ID_CATEGORIA, ID_ESTADO INTO V_CATEGORIA_PARTIDO, V_ESTADO_PARTIDO FROM FIDE_PARTIDOS_TB WHERE ID_PARTIDO = :NEW.ID_PARTIDO;
    SELECT COUNT(*) INTO V_ASISTIO FROM FIDE_ASISTENCIA_TB WHERE ID_PARTIDO = :NEW.ID_PARTIDO AND ID_JUGADOR = :NEW.ID_JUGADOR AND ID_ESTADO IN (1, 4);
    IF V_ESTADO_JUGADOR <> 1 OR V_CATEGORIA_JUGADOR <> V_CATEGORIA_PARTIDO OR V_ASISTIO = 0 THEN
        RAISE_APPLICATION_ERROR(-20004, 'El jugador debe estar activo, asistir y pertenecer a la categoria del partido.');
    END IF;
    IF V_ESTADO_PARTIDO <> 4 THEN
        RAISE_APPLICATION_ERROR(-20005, 'Solo se pueden registrar estadisticas para partidos completados.');
    END IF;
END FIDE_ESTADISTICA_JUGADOR_VALIDAR_TRG;
/

