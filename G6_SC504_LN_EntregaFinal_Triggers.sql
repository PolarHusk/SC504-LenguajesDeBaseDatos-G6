CREATE OR REPLACE TRIGGER FIDE_ESTADISTICA_JUGADOR_MARCADOR_TRG
AFTER INSERT OR UPDATE OF GOLES, ID_ESTADO, ID_PARTIDO OR DELETE ON FIDE_ESTADISTICA_JUGADOR_TB
FOR EACH ROW
DECLARE
    V_GOLES_OLD NUMBER := 0;
    V_GOLES_NEW NUMBER := 0;
BEGIN
    IF INSERTING OR UPDATING THEN
        V_GOLES_NEW := CASE WHEN :NEW.ID_ESTADO IN (1, 4) THEN NVL(:NEW.GOLES, 0) ELSE 0 END;
        UPDATE FIDE_PARTIDOS_TB SET GOLES_FAVOR = NVL(GOLES_FAVOR, 0) + V_GOLES_NEW WHERE ID_PARTIDO = :NEW.ID_PARTIDO;
    END IF;
    IF DELETING OR UPDATING THEN
        V_GOLES_OLD := CASE WHEN :OLD.ID_ESTADO IN (1, 4) THEN NVL(:OLD.GOLES, 0) ELSE 0 END;
        UPDATE FIDE_PARTIDOS_TB SET GOLES_FAVOR = GREATEST(NVL(GOLES_FAVOR, 0) - V_GOLES_OLD, 0) WHERE ID_PARTIDO = :OLD.ID_PARTIDO;
    END IF;
END FIDE_ESTADISTICA_JUGADOR_MARCADOR_TRG;
/

CREATE OR REPLACE TRIGGER FIDE_ESTADISTICA_JUGADOR_EQUIPO_TRG
AFTER INSERT OR UPDATE OF PASES, PASES_EXITOSOS, TIROS, TIROS_EXITOSOS, ID_ESTADO, ID_PARTIDO OR DELETE ON FIDE_ESTADISTICA_JUGADOR_TB
FOR EACH ROW
DECLARE
    V_FACTOR_OLD NUMBER := 0;
    V_FACTOR_NEW NUMBER := 0;
BEGIN
    IF INSERTING OR UPDATING THEN
        V_FACTOR_NEW := CASE WHEN :NEW.ID_ESTADO IN (1, 4) THEN 1 ELSE 0 END;
        MERGE INTO FIDE_ESTADISTICA_EQUIPO_TB EE USING (SELECT :NEW.ID_PARTIDO AS ID_PARTIDO FROM DUAL) X ON (EE.ID_PARTIDO = X.ID_PARTIDO)
        WHEN MATCHED THEN UPDATE SET EE.TIROS = NVL(EE.TIROS, 0) + (NVL(:NEW.TIROS, 0) * V_FACTOR_NEW), EE.TIROS_PORTERIA = NVL(EE.TIROS_PORTERIA, 0) + (NVL(:NEW.TIROS_EXITOSOS, 0) * V_FACTOR_NEW), EE.PASES_EXITOSOS = NVL(EE.PASES_EXITOSOS, 0) + (NVL(:NEW.PASES_EXITOSOS, 0) * V_FACTOR_NEW), EE.PASES_FALLIDOS = NVL(EE.PASES_FALLIDOS, 0) + ((NVL(:NEW.PASES, 0) - NVL(:NEW.PASES_EXITOSOS, 0)) * V_FACTOR_NEW)
        WHEN NOT MATCHED THEN INSERT (ID_ESTADISTICA_EQUIPO, TIROS, TIROS_PORTERIA, PASES_EXITOSOS, PASES_FALLIDOS, ID_PARTIDO, ID_ESTADO)
        VALUES (ID_ESTADISTICA_EQUIPO_SEQ.NEXTVAL, NVL(:NEW.TIROS, 0) * V_FACTOR_NEW, NVL(:NEW.TIROS_EXITOSOS, 0) * V_FACTOR_NEW, NVL(:NEW.PASES_EXITOSOS, 0) * V_FACTOR_NEW, (NVL(:NEW.PASES, 0) - NVL(:NEW.PASES_EXITOSOS, 0)) * V_FACTOR_NEW, :NEW.ID_PARTIDO, 1);
    END IF;
    IF DELETING OR UPDATING THEN
        V_FACTOR_OLD := CASE WHEN :OLD.ID_ESTADO IN (1, 4) THEN 1 ELSE 0 END;
        UPDATE FIDE_ESTADISTICA_EQUIPO_TB
        SET TIROS = GREATEST(NVL(TIROS, 0) - (NVL(:OLD.TIROS, 0) * V_FACTOR_OLD), 0), TIROS_PORTERIA = GREATEST(NVL(TIROS_PORTERIA, 0) - (NVL(:OLD.TIROS_EXITOSOS, 0) * V_FACTOR_OLD), 0), PASES_EXITOSOS = GREATEST(NVL(PASES_EXITOSOS, 0) - (NVL(:OLD.PASES_EXITOSOS, 0) * V_FACTOR_OLD), 0), PASES_FALLIDOS = GREATEST(NVL(PASES_FALLIDOS, 0) - ((NVL(:OLD.PASES, 0) - NVL(:OLD.PASES_EXITOSOS, 0)) * V_FACTOR_OLD), 0)
        WHERE ID_PARTIDO = :OLD.ID_PARTIDO;
    END IF;
END FIDE_ESTADISTICA_JUGADOR_EQUIPO_TRG;
